// Ordered Set Tree
// S.order_of_key (k) : Number of items strictly smaller than k .
// S.find_by_order(k) : K-th element in a set (counting from zero).


void solve(){

  int n; cin >> n;
  string s; cin >> s;
  vector<int> diff(n);
  int cnta = 0, cntb = 0;
  for(int i=0;i<n;i++){
    if(s[i] == 'A') cnta++;
    if(s[i] == 'B') cntb++;
    diff[i] = cnta - cntb;
  }

  ordered_set os;
  int ans = 0;
  for(int i=n-1;i>=0;i--){
    int x = diff[i];
    os.insert(x);
    if(s[i] == 'A'){
      ans += os.size() - os.order_of_key(x);
    } else if(s[i] == 'B'){
      ans += os.size() - os.order_of_key(x + 2);
    } else {
      ans += os.size() - os.order_of_key(x+1);
    }
  }
  cout << ans << endl;

}


